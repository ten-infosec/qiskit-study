"""
Q1 실습: NumPy로 양자 게이트 직접 만들어보기

오늘 손으로 확인한 것
- 큐비트 상태는 벡터, 게이트는 행렬, 게이트를 거는 건 행렬 곱셈이다
- 진폭을 제곱하면 확률이 된다 (0.707² ≈ 0.5 → 50:50)
- 마이너스 부호(위상)는 측정으로는 안 보이지만 결과를 바꿀 수 있다
- H를 두 번 걸면 간섭으로 원래 상태로 돌아온다 → 모듈 1의 {'0': 1024}의 이유
- Qiskit이 속에서 하는 일도 결국 이 행렬 곱셈이다
"""


# 1단계: 큐비트 상태 |0>, |1>을 벡터로 만들기


import numpy as np

ket0 = np.array([1, 0])
ket1 = np.array([0, 1])

print("|0> =", ket0)
print("|1> =", ket1)


# -> numpy를 np라는 짧은 이름으로 불러오겠다 (거의 모든 파이썬 코드가 이 별명을 씀)
# -> |0> 상태를 [1, 0] 벡터로 만들겠다 (첫 칸 = 0이 나올 진폭)
# -> |1> 상태를 [0, 1] 벡터로 만들겠다 (둘째 칸 = 1이 나올 진폭)
# -> 리스트가 아니라 NumPy 배열로 만드는 이유: 그래야 행렬 곱셈(@)을 할 수 있음
# -> 두 상태를 화면에 출력하겠다 (쉼표로 구분하면 글자와 값을 이어서 출력)
#
# 실행 결과: |0> = [1 0] / |1> = [0 1]
# 진폭을 제곱하면 확률 → [1, 0]이면 0이 나올 확률 1² = 100%




# 2단계: X, Z, H 게이트를 행렬로 만들고 상태에 곱하기


X = np.array([[0, 1],
              [1, 0]])
Z = np.array([[1, 0],
              [0, -1]])
H = np.array([[1, 1],
              [1, -1]]) / np.sqrt(2)

print("X|0> =", X @ ket0)
print("X|1> =", X @ ket1)
print("Z|1> =", Z @ ket1)
print("H|0> =", H @ ket0)
print("H|1> =", H @ ket1)


# -> X 게이트 = 0과 1을 뒤바꾸는 행렬을 만들겠다 (고전 컴퓨터의 NOT)
# -> Z 게이트 = |1> 쪽에만 마이너스 부호를 붙이는 행렬을 만들겠다
# -> H 게이트 = 0과 1을 반반 섞는 행렬을 만들겠다 (√2로 나눠 길이를 1로 맞춤)
# -> @ 기호로 "행렬 x 벡터" 곱셈을 하겠다 = 게이트를 큐비트에 거는 것
#
# 실행 결과
#   X|0> = [0 1]            → 0이 1로 뒤집힘
#   Z|1> = [0 -1]           → 부호만 바뀜, (-1)² = 1이라 측정 확률은 그대로 = 위상
#   H|0> = [0.707 0.707]    → 0.707² ≈ 0.5 → 50:50 (모듈 1에서 밥의 H를 뺐을 때 결과)
#   H|1> = [0.707 -0.707]   → 확률은 50:50으로 같고 부호만 다름 (|−> 상태)




# 3단계: H x H = I (아무것도 안 하는 행렬) 확인


I = np.round(H @ H, 10)

print("H x H =")
print(I)
print("H(H|0>) =", np.round(H @ (H @ ket0), 10))
print("H(H|1>) =", np.round(H @ (H @ ket1), 10))


# -> H 행렬끼리 곱하고, 소수점 10자리에서 반올림해서 I에 담겠다
#    (컴퓨터는 √2를 정확히 저장 못 해서 생기는 아주 작은 오차를 정리하기 위해)
# -> |0>에 H를 두 번 걸면 다시 |0>이 되는지 보겠다
# -> |1>에 H를 두 번 걸면 다시 |1>이 되는지 보겠다
#
# 실행 결과: [[1. -0.] [-0. 1.]] = 단위행렬 I
#   -0.은 아주 작은 음수 오차가 반올림된 흔적, 값은 0과 같음
#
# 간섭: 두 번째 H에서 0 쪽은 0.5 + 0.5 = 1로 커지고, 1 쪽은 0.5 - 0.5 = 0으로 상쇄
#   → 모듈 1의 H-barrier-H가 {'0': 1024}로 100% 0이 나온 이유




# 4단계: 내가 만든 행렬 계산과 Qiskit 결과 비교


from qiskit import QuantumCircuit
from qiskit.quantum_info import Statevector

qc = QuantumCircuit(1)
qc.h(0)

sv = Statevector.from_instruction(qc)

print("Qiskit H|0> =", sv.data)
print("같은가?", np.allclose(sv.data, H @ ket0))


# -> Qiskit에서 회로 만드는 도구와 상태벡터 계산 도구를 불러오겠다
# -> 큐비트 1개짜리 회로를 만들겠다
# -> 0번 큐비트에 H 게이트를 걸겠다
# -> 회로를 측정하지 않고, 측정 직전의 진폭 벡터를 그대로 계산하겠다
#    (모듈 1은 측정 횟수 {'0': 522, '1': 502}를 봤고, 이건 그 확률의 원재료인 진폭을 봄)
# -> Qiskit이 계산한 진폭을 출력하겠다
# -> np.allclose로 내 계산과 "거의 같은지" 확인하겠다
#    (컴퓨터 계산엔 작은 오차가 생겨서 ==로 비교하면 틀렸다고 나올 수 있음)
#
# 실행 결과: [0.70710678+0.j 0.70710678+0.j] / 같은가? True
#   +0.j = 복소수의 허수 부분이 0 (파이썬은 허수 단위를 i 대신 j로 씀)